        public static string ActionName(PowerAction a)
        {
            return T("act." + Key(a));
        }

        public static string Key(PowerAction a)
        {
            switch (a)
            {
                case PowerAction.Sleep: return "sleep";
                case PowerAction.Hibernate: return "hibernate";
                case PowerAction.Restart: return "restart";
                case PowerAction.Lock: return "lock";
                case PowerAction.Logoff: return "logoff";
                default: return "shutdown";
            }
        }

        // "afsluiten", voor midden in een zin
        public static string ActionLower(PowerAction a)
        {
            string n = ActionName(a);
            return n.Length > 0 ? char.ToLowerInvariant(n[0]) + n.Substring(1) : n;
        }

        // De regel boven de knop: wat er gebeurt als je op Enter drukt
        public static string Info(PowerAction a, TimeChoice t, int delaySeconds, DateTime now)
        {
            if (t.IsNow)
                return delaySeconds > 0 ? F("info.delay", ActionLower(a), delaySeconds) : F("info.instant", ActionLower(a));
            DateTime target = t.TargetFrom(now);
            if (t.IsClock)
                return ActionName(a) + " " + F("at", TimeInput.Label(t)) + ", " + F("in", TimeInput.Duration((int)Math.Round((target - now).TotalMinutes)));
            return Phrase(a, t) + ", " + F("at", target.ToString("HH:mm"));
        }

        // "Nu afsluiten", "Afsluiten over 30 min", "Afsluiten om 23:30"
        public static string Phrase(PowerAction a, TimeChoice t)
        {
            if (t.IsNow) return T("now." + Key(a));
            string when = t.IsClock ? F("at", TimeInput.Label(t)) : F("in", TimeInput.Label(t));
            return ActionName(a) + " " + when;
        }
